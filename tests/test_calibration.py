"""Act VI, quests 6.2 to 6.4: Heston and SVI calibration, historical correlation.

Two kinds of test, kept apart on purpose.

1. Synthetic (always run): the calibrator is fed quotes generated by a known
   model, with no noise, and must recover them. This checks the machinery:
   pricing, residual units, optimiser, bounds. It says nothing about the market.

2. Real-data (read the committed results in data/): the thresholds below were
   written into this file BEFORE the final calibration was read. A threshold
   that is missed is reported as a finding, not moved.
     - 6.2 Heston, per name, joint over expiries: share of quotes inside the
       bid-ask band (|residual| <= 1 half-spread) >= 0.80.
     - 6.3 SVI, per expiry: same share, quote-weighted, >= 0.80.
     - 6.4 correlation: GLD-SLV positive and above 0.5; matrix PSD after repair.
"""

import sys, pathlib, json, glob
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "src"))

import numpy as np
import pandas as pd
import pytest

from calibration import (calibrate_heston, calibrate_svi_slice, heston_calls_grid,
                         heston_model_calls_fast, svi_model_calls)
from correlation import historical_correlation
from heston import heston_call

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
R = 0.04


def _grid_quotes(model_fn, params, expiries):
    rows = []
    for name, T in expiries:
        for k in np.linspace(-0.15, 0.15, 13):
            rows.append(dict(expiry=name, T=T, F=100.0, K=100.0 * np.exp(k), C_mid=0.0, half=0.02))
    q = pd.DataFrame(rows)
    q["C_mid"] = model_fn(q, params, R)
    return q


