def _latest(pattern):
    files = sorted(glob.glob(str(DATA / pattern)))
    assert files, f"no {pattern} in data/"
    return json.load(open(files[-1]))


@pytest.mark.xfail(strict=True, reason="FINDING 6.2: joint Heston misses the band on the term snapshot (GLD 21%, SLV 33%, USO 70%)")
@pytest.mark.parametrize("name", ["GLD", "SLV", "USO"])
def test_heston_calibration_reel_dans_la_bande(name):
    """6.2: per-name joint Heston, share of quotes inside the bid-ask band >= 0.80."""
    res = _latest("heston_calibration_*.json")
    assert res[name]["frac_inside"] >= 0.80, (
        f"{name}: {res[name]['frac_inside']:.3f} inside the band, median |res| "
        f"{res[name]['median_abs_res']:.2f} half-spreads; params {res[name]['params']}")


@pytest.mark.parametrize("name", ["GLD", "SLV", "USO"])
def test_svi_calibration_reel_dans_la_bande(name):
    """6.3: per-expiry SVI, quote-weighted share inside the band >= 0.80, and no slice
    with negative total variance."""
    res = _latest("svi_calibration_*.json")["names"][name]
    assert res["frac_inside"] >= 0.80, f"{name}: {res['frac_inside']:.3f} inside the band"
    for expiry, s in res["slices"].items():
        assert s["min_total_variance"] >= 0.0, f"{name} {expiry}: negative total variance"


def test_correlation_reelle_signe_et_psd():
    """6.4: GLD-SLV correlation > 0.5 (declared in advance), and the repaired matrix
    is a valid correlation matrix (unit diagonal, eigenvalues >= 0)."""
    hist = pd.read_csv(DATA / "history.csv", index_col=0, parse_dates=True)
    raw, repaired = historical_correlation(hist)
    names = list(hist.columns)
    g, s = names.index("GLD"), names.index("SLV")
    assert raw[g, s] > 0.5
    assert np.allclose(np.diag(repaired), 1.0)
    assert np.linalg.eigvalsh(repaired).min() >= -1e-12


def test_correlation_synthetique_retrouve_la_cible():
    """6.4 machinery: correlated log-normal prices with known rho are recovered."""
    rng = np.random.default_rng(12)
    n, rho = 20_000, 0.7
    z = rng.standard_normal((n, 2))
    z[:, 1] = rho * z[:, 0] + np.sqrt(1 - rho**2) * z[:, 1]
    prices = pd.DataFrame(np.exp(np.cumsum(0.01 * z, axis=0)), columns=["A", "B"])
    raw, repaired = historical_correlation(prices)
    assert abs(raw[0, 1] - rho) < 4 / np.sqrt(n)
    assert np.allclose(repaired, repaired.T)


