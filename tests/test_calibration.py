def test_heston_calls_grid_egal_quad():
    """The quadrature pricer equals the quad-based heston_call, to 1e-7 of spot."""
    p = dict(v0=0.02, kappa=3.0, theta=0.06, xi=1.0, rho=-0.5)
    S = 48.7
    Ks = np.array([0.9, 0.97, 1.0, 1.03, 1.1]) * S
    for T in (0.003, 0.25, 1.0):
        fast = heston_calls_grid(S, Ks, T, p, R)
        ref = np.array([heston_call(S, K, p["v0"], R, T, p["kappa"], p["theta"], p["xi"], p["rho"])
                        for K in Ks])
        assert np.max(np.abs(fast - ref)) < 1e-7 * S


def test_calibrate_heston_retrouve_les_parametres_synthetiques():
    """Noiseless quotes from known Heston parameters: residuals vanish, params return.

    Identifiability is good here (three expiries, a full strike range), so the
    parameters themselves are checked, not only the fit.
    """
    truth = dict(v0=0.05, kappa=2.0, theta=0.05, xi=0.6, rho=-0.6)
    q = _grid_quotes(heston_model_calls_fast, truth,
                     [("a", 0.01), ("b", 0.02), ("c", 0.05)])
    res = calibrate_heston(q, R, [[0.04, 1.5, 0.04, 0.5, -0.5], [0.01, 5.0, 0.01, 1.0, -0.8]])
    assert res["max_abs_res"] < 1e-6
    for name, value in truth.items():
        assert abs(res["params"][name] - value) < 1e-3, name


def test_svi_retrouve_la_tranche_synthetique():
    """Noiseless SVI slice: the fit reproduces it, and the total variance stays >= 0."""
    truth = dict(a=0.02, b=0.2, rho=-0.5, m=0.02, sigma=0.15)
    q = _grid_quotes(svi_model_calls, truth, [("x", 0.5)])
    res = calibrate_svi_slice(q, R)
    assert res["max_abs_res"] < 1e-6
    assert res["min_total_variance"] >= 0.0


